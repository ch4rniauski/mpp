while True:
    text = input("Введите первое целое число: ")
    try:
        a = int(text)
        break
    except Exception:
        print("Ошибка: нужно ввести целое число. Попробуйте снова.")

while True:
    text = input("Введите второе целое число: ")
    try:
        b = int(text)
        break
    except Exception:
        print("Ошибка: нужно ввести целое число. Попробуйте снова.")

print("\n--- Арифметические операции ---")
print(f"Сумма: {a} + {b} = {a + b}")
print(f"Разность: {a} - {b} = {a - b}")
print(f"Произведение: {a} * {b} = {a * b}")

if b == 0:
    print("Деление на ноль невозможно")
else:
    print(f"Частное: {a} / {b} = {a / b:.2f}")
    print(f"Целочисленное деление: {a} // {b} = {a // b}")
    print(f"Остаток от деления: {a} % {b} = {a % b}")

print(f"Возведение в степень: {a} ** {b} = {a ** b}")

print("\n--- Побитовые операции ---")
print(f"Побитовое И: {a} & {b} = {a & b}")
print(f"Побитовое ИЛИ: {a} | {b} = {a | b}")
print(f"Побитовое исключающее ИЛИ: {a} ^ {b} = {a ^ b}")
print(f"Побитовая инверсия первого числа: ~{a} = {~a}")
print(f"Побитовая инверсия второго числа: ~{b} = {~b}")

if b < 0:
    print(f"Количество бит сдвига не может быть отрицательным ({b})")
else:
    print(f"Сдвиг влево: {a} << {b} = {a << b}")
    print(f"Сдвиг вправо: {a} >> {b} = {a >> b}")
